-- BORRA BASE DE DATOS
DROP DATABASE IF EXISTS conservatorio_castella;

-- PASO 1 CREAR BASE DE DATOS
CREATE DATABASE conservatorio_castella CHARACTER SET utf8mb4;

-- PASO 2 SELECCIONAR BASE DE DATOS
USE conservatorio_castella;

-- PASO 3 CREAR TABLA ESTUDIANTES
CREATE TABLE ESTUDIANTES(
    CEDULA VARCHAR(15) NOT NULL,
    NOMBRE VARCHAR(25) NOT NULL,
    APELLIDOS VARCHAR(30) NOT NULL,
    FECHA_NACIMIENTO DATE NOT NULL,
    TELEFONO VARCHAR(15) NOT NULL,
    CORREO_ELECTRONICO VARCHAR(100) NOT NULL,
    NACIONALIDAD VARCHAR(15) NOT NULL,
    PRIMARY KEY(CEDULA)
) ENGINE InnoDB;

-- PASO 4 CREAR TABLA GRUPOS
CREATE TABLE GRUPOS(
    COD_GRUPO VARCHAR(10) NOT NULL,
    SECCION VARCHAR(10) NOT NULL,
    PRIMARY KEY(COD_GRUPO)
) ENGINE InnoDB;

-- PASO 5 CREAR TABLA PROFESORES
CREATE TABLE PROFESORES(
    COD_PROFESOR VARCHAR(10) NOT NULL,
    CEDULA VARCHAR(15) NOT NULL,
    NOMBRE VARCHAR(25) NOT NULL,
    APELLIDOS VARCHAR(30) NOT NULL,
    ESPECIALIDAD VARCHAR(30) NOT NULL,
    TELEFONO VARCHAR(15) NOT NULL,
    CORREO_ELECTRONICO VARCHAR(100) NOT NULL,
    PRIMARY KEY(COD_PROFESOR)
) ENGINE InnoDB;

-- PASO 6 CREAR TABLA INSTRUMENTOS
CREATE TABLE INSTRUMENTOS(
    COD_INSTRUMENTO VARCHAR(10) NOT NULL,
    NOMBRE VARCHAR(30) NOT NULL,
    TIPO VARCHAR(20) NOT NULL,
    MARCA VARCHAR(20) NOT NULL,
    ESTADO VARCHAR(15) NOT NULL,
    PRIMARY KEY(COD_INSTRUMENTO)
) ENGINE InnoDB;

-- PASO 7 CREAR TABLA MATERIAS
CREATE TABLE MATERIAS(
    COD_MATERIA VARCHAR(10) NOT NULL,
    NOMBRE VARCHAR(30) NOT NULL,
    CREDITOS INT NOT NULL,
    NIVEL VARCHAR(15) NOT NULL,
    PRIMARY KEY(COD_MATERIA)
) ENGINE InnoDB;

-- PASO 8 CREAR TABLA AULAS
CREATE TABLE AULAS(
    COD_AULA VARCHAR(10) NOT NULL,
    NOMBRE VARCHAR(20) NOT NULL,
    CAPACIDAD INT NOT NULL,
    TIPO VARCHAR(20) NOT NULL,
    PRIMARY KEY(COD_AULA)
) ENGINE InnoDB;

-- PASO 9 CREAR TABLA MATRICULAS
CREATE TABLE MATRICULAS(
    COD_MATRICULA VARCHAR(10) NOT NULL,
    FECHA_MATRICULA DATE NOT NULL,
    ANIO_LECTIVO INT NOT NULL,
    PRIMARY KEY(COD_MATRICULA)
) ENGINE InnoDB;

-- AGREGAR COLUMNAS A LAS TABLAS
ALTER TABLE ESTUDIANTES ADD SEXO VARCHAR(10) NOT NULL;
ALTER TABLE ESTUDIANTES ADD DIRECCION VARCHAR(50) NOT NULL;
ALTER TABLE ESTUDIANTES ADD CODIGO_GRUPO VARCHAR(10) NOT NULL;

ALTER TABLE MATRICULAS ADD CEDULA_ESTUDIANTE VARCHAR(15) NOT NULL;
ALTER TABLE MATRICULAS ADD COD_MATERIA VARCHAR(10) NOT NULL;
ALTER TABLE MATRICULAS ADD COD_PROFESOR VARCHAR(10) NOT NULL;
ALTER TABLE MATRICULAS ADD COD_AULA VARCHAR(10) NOT NULL;
ALTER TABLE MATRICULAS ADD COD_INSTRUMENTO VARCHAR(10) NOT NULL;

-- CREAR RELACIONES ENTRE TABLAS "LLAVES FORANEAS"
ALTER TABLE ESTUDIANTES ADD CONSTRAINT FK_GRUPOS
    FOREIGN KEY (CODIGO_GRUPO) REFERENCES GRUPOS(COD_GRUPO);

ALTER TABLE MATRICULAS ADD CONSTRAINT FK_ESTUDIANTE
    FOREIGN KEY (CEDULA_ESTUDIANTE) REFERENCES ESTUDIANTES(CEDULA);

ALTER TABLE MATRICULAS ADD CONSTRAINT FK_MATERIA
    FOREIGN KEY (COD_MATERIA) REFERENCES MATERIAS(COD_MATERIA);

ALTER TABLE MATRICULAS ADD CONSTRAINT FK_PROFESOR
    FOREIGN KEY (COD_PROFESOR) REFERENCES PROFESORES(COD_PROFESOR);

ALTER TABLE MATRICULAS ADD CONSTRAINT FK_AULA
    FOREIGN KEY (COD_AULA) REFERENCES AULAS(COD_AULA);

ALTER TABLE MATRICULAS ADD CONSTRAINT FK_INSTRUMENTO
    FOREIGN KEY (COD_INSTRUMENTO) REFERENCES INSTRUMENTOS(COD_INSTRUMENTO);

-- AGREGAR RESTRICCIONES DE VALORES UNICOS
ALTER TABLE ESTUDIANTES ADD CONSTRAINT UQ_CORREO_ESTUDIANTE UNIQUE (CORREO_ELECTRONICO);
ALTER TABLE PROFESORES ADD CONSTRAINT UQ_CEDULA_PROFESOR UNIQUE (CEDULA);
ALTER TABLE PROFESORES ADD CONSTRAINT UQ_CORREO_PROFESOR UNIQUE (CORREO_ELECTRONICO);

